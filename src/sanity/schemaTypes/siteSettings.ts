import { defineField, defineType, defineArrayMember } from 'sanity'
import { CogIcon } from '@sanity/icons/Cog'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  icon: CogIcon,
  groups: [
    { name: 'general', title: 'General', default: true },
    { name: 'visit', title: 'Address & hours' },
    { name: 'social', title: 'Social media' },
    { name: 'bee', title: 'The bee' },
    { name: 'reviews', title: 'Reviews' },
    { name: 'newsletter', title: 'Newsletter' },
    { name: 'seo', title: 'Google & sharing' },
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Café name',
      type: 'string',
      group: 'general',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'tagline',
      title: 'Short tagline',
      type: 'string',
      group: 'general',
      description: 'Appears in the footer, e.g. "Coffee, honey & a little haven on The Parade."',
    }),
    defineField({
      name: 'announcement',
      title: 'Announcement bar (optional)',
      type: 'string',
      group: 'general',
      description: 'A one-line message at the very top of every page, e.g. "Pumpkin spice lattes are back". Leave empty to hide it.',
    }),
    defineField({
      name: 'announcementLink',
      title: 'Announcement bar link (optional)',
      type: 'object',
      group: 'general',
      description: 'Where people go when they tap the announcement.',
      hidden: ({ document }) => !document?.announcement,
      fields: [
        defineField({
          name: 'page',
          title: 'Go to',
          type: 'string',
          options: {
            list: [
              { title: 'Nowhere (just text)', value: '' },
              { title: 'Home page', value: '/' },
              { title: 'Menu', value: '/menu' },
              { title: 'Shop', value: '/shop' },
              { title: 'About', value: '/about' },
              { title: 'Blog', value: '/blog' },
              { title: 'Opening hours & map', value: '/#visit' },
              { title: 'Another page or website…', value: 'custom' },
            ],
          },
        }),
        defineField({
          name: 'menuSection',
          title: 'Menu section (optional)',
          type: 'reference',
          to: [{ type: 'menuCategory' }],
          description: 'Jump straight to one part of the menu, e.g. Autumn Specials.',
          hidden: ({ parent }) => parent?.page !== '/menu',
        }),
        defineField({
          name: 'url',
          title: 'Web address',
          type: 'string',
          description: 'A page on this site like /shop/pure-honey, or a full link like https://instagram.com/…',
          hidden: ({ parent }) => parent?.page !== 'custom',
          validation: (r) =>
            r.custom((v, ctx) => {
              const parent = ctx.parent as { page?: string } | undefined
              if (parent?.page !== 'custom') return true
              if (!v) return 'Add the web address'
              return /^(\/|https?:\/\/|mailto:|tel:)/.test(v) || 'Start with / for a page on this site, or https:// for another website'
            }),
        }),
      ],
    }),
    defineField({
      name: 'address',
      title: 'Address',
      type: 'text',
      rows: 3,
      group: 'visit',
    }),
    defineField({
      name: 'mapQuery',
      title: 'Google Maps search',
      type: 'string',
      group: 'visit',
      description: 'What to search on Google Maps to find you. Usually your name + postcode.',
    }),
    defineField({ name: 'phone', title: 'Phone', type: 'string', group: 'visit' }),
    defineField({ name: 'email', title: 'Email', type: 'string', group: 'visit', validation: (rule) => rule.email() }),
    defineField({
      name: 'hours',
      title: 'Opening hours',
      type: 'array',
      group: 'visit',
      of: [defineArrayMember({ type: 'openingHours' })],
    }),
    defineField({
      name: 'hoursNote',
      title: 'Note under opening hours',
      type: 'string',
      group: 'visit',
      initialValue: 'Festive and bank holiday hours may differ.',
    }),
    defineField({
      name: 'specialHours',
      title: 'Holiday & special hours',
      type: 'array',
      group: 'visit',
      description: 'Add bank holidays, Christmas or days you’re closed. They show on the website automatically in the weeks before, and disappear once the day has passed.',
      of: [defineArrayMember({ type: 'specialHours' })],
    }),
    defineField({
      name: 'instagram',
      title: 'Instagram link',
      type: 'url',
      group: 'social',
      description: 'Full link, e.g. https://instagram.com/yourname',
    }),
    defineField({ name: 'tiktok', title: 'TikTok link', type: 'url', group: 'social' }),
    defineField({ name: 'facebook', title: 'Facebook link', type: 'url', group: 'social' }),
    defineField({
      name: 'beeEnabled',
      title: 'Show the bee',
      type: 'boolean',
      group: 'bee',
      initialValue: true,
      description: 'The little bee in the corner of every page. Visitors tap it to send you feedback and ideas (they arrive in Inbox), and to see your recommendations.',
    }),
    defineField({
      name: 'beeGreeting',
      title: 'What the bee says',
      type: 'string',
      group: 'bee',
      initialValue: 'Got an idea, a wish or a kind word? Tell the bee.',
    }),
    defineField({
      name: 'beePicks',
      title: 'The bee recommends',
      type: 'array',
      group: 'bee',
      description: 'Up to four things to try. Change them whenever you like, e.g. this month’s special.',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'beePick',
          fields: [
            defineField({ name: 'title', title: 'Name', type: 'string', validation: (r) => r.required() }),
            defineField({ name: 'text', title: 'Why it’s good', type: 'string' }),
            defineField({ name: 'link', title: 'Link (optional)', type: 'string', description: 'A page on this site like /menu or /shop/pure-honey, or a full web address.' }),
          ],
        }),
      ],
      validation: (r) => r.max(4),
    }),
    defineField({
      name: 'googlePlaceId',
      title: 'Google Place ID',
      type: 'string',
      group: 'reviews',
      description:
        'Lets the website show your Google rating and best reviews, and link straight to “Write a review”. Find it by searching for the café at developers.google.com/maps/documentation/places/web-service/place-id (it starts with ChIJ…).',
    }),
    defineField({
      name: 'reviewLink',
      title: '“Leave a review” link (optional)',
      type: 'url',
      group: 'reviews',
      description: 'Only if you want the button to go somewhere other than Google, e.g. TripAdvisor.',
    }),
    defineField({
      name: 'newsletter',
      title: 'Newsletter signup',
      type: 'object',
      group: 'newsletter',
      description:
        'The “Stay in the hive” signup above the footer and the pop-up. Subscribers go to your Brevo account, where you write and send the newsletters and the welcome email with the discount code.',
      options: { collapsible: false },
      fields: [
        defineField({ name: 'enabled', title: 'Show the newsletter signup', type: 'boolean', initialValue: true }),
        defineField({
          name: 'popup',
          title: 'Also show the pop-up',
          type: 'boolean',
          initialValue: true,
          description: 'A small card that slides in once per visitor. It never comes back after they subscribe, and stays away for 30 days if they close it.',
        }),
        defineField({
          name: 'popupDelay',
          title: 'Pop-up delay (seconds)',
          type: 'number',
          initialValue: 20,
          description: 'How long someone browses before the pop-up appears.',
          validation: (r) => r.min(5).max(120).integer(),
          hidden: ({ parent }) => parent?.popup === false,
        }),
        defineField({
          name: 'popupHeading',
          title: 'Pop-up heading',
          type: 'string',
          initialValue: 'Enjoy 10% off your first visit',
          hidden: ({ parent }) => parent?.popup === false,
        }),
        defineField({
          name: 'popupText',
          title: 'Pop-up text',
          type: 'text',
          rows: 2,
          initialValue: 'Join the Honey & Haven letter.',
          hidden: ({ parent }) => parent?.popup === false,
        }),
        defineField({ name: 'heading', title: 'Footer signup heading', type: 'string', initialValue: 'Stay in the hive' }),
        defineField({
          name: 'text',
          title: 'Footer signup text',
          type: 'text',
          rows: 2,
          initialValue: 'Coffee notes, local stories and occasional treats — plus 10% off your first visit.',
        }),
        defineField({
          name: 'offer',
          title: 'Discount code wording',
          type: 'string',
          initialValue: 'Your 10% welcome code arrives by email as soon as you confirm.',
          description: 'Shown under both forms. The code itself lives in the welcome email in Brevo, so it isn’t shown on the website.',
        }),
        defineField({ name: 'button', title: 'Button label', type: 'string', initialValue: 'Subscribe' }),
        defineField({
          name: 'thanks',
          title: 'After signing up',
          type: 'text',
          rows: 2,
          initialValue: 'Thank you! Check your inbox and tap the link to confirm. Your 10% code follows straight after.',
          description: 'Replaces the form once someone has signed up.',
        }),
      ],
    }),
    defineField({
      name: 'seo',
      title: 'Default Google & sharing settings',
      type: 'seo',
      group: 'seo',
      description: 'Used on every page unless that page has its own.',
    }),
  ],
  preview: { prepare: () => ({ title: 'Site settings' }) },
})
