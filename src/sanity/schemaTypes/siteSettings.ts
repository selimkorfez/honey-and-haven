import { defineField, defineType, defineArrayMember } from 'sanity'
import { CogIcon } from '@sanity/icons/Cog'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  icon: CogIcon,
  groups: [
    { name: 'general', title: 'General', default: true },
    { name: 'visit', title: 'Address & hours' },
    { name: 'social', title: 'Social media' },
    { name: 'bee', title: 'The bee' },
    { name: 'reviews', title: 'Reviews' },
    { name: 'seo', title: 'Google & sharing' },
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Café name',
      type: 'string',
      group: 'general',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'tagline',
      title: 'Short tagline',
      type: 'string',
      group: 'general',
      description: 'Appears in the footer, e.g. "Coffee, honey & a little haven on The Parade."',
    }),
    defineField({
      name: 'announcement',
      title: 'Announcement bar (optional)',
      type: 'string',
      group: 'general',
      description: 'A one-line message at the very top of every page, e.g. "Pumpkin spice lattes are back". Leave empty to hide it.',
    }),
    defineField({
      name: 'address',
      title: 'Address',
      type: 'text',
      rows: 3,
      group: 'visit',
    }),
    defineField({
      name: 'mapQuery',
      title: 'Google Maps search',
      type: 'string',
      group: 'visit',
      description: 'What to search on Google Maps to find you. Usually your name + postcode.',
    }),
    defineField({ name: 'phone', title: 'Phone', type: 'string', group: 'visit' }),
    defineField({ name: 'email', title: 'Email', type: 'string', group: 'visit', validation: (rule) => rule.email() }),
    defineField({
      name: 'hours',
      title: 'Opening hours',
      type: 'array',
      group: 'visit',
      of: [defineArrayMember({ type: 'openingHours' })],
    }),
    defineField({
      name: 'hoursNote',
      title: 'Note under opening hours',
      type: 'string',
      group: 'visit',
      initialValue: 'Festive and bank holiday hours may differ.',
    }),
    defineField({
      name: 'specialHours',
      title: 'Holiday & special hours',
      type: 'array',
      group: 'visit',
      description: 'Add bank holidays, Christmas or days you’re closed. They show on the website automatically in the weeks before, and disappear once the day has passed.',
      of: [defineArrayMember({ type: 'specialHours' })],
    }),
    defineField({
      name: 'instagram',
      title: 'Instagram link',
      type: 'url',
      group: 'social',
      description: 'Full link, e.g. https://instagram.com/yourname',
    }),
    defineField({ name: 'tiktok', title: 'TikTok link', type: 'url', group: 'social' }),
    defineField({ name: 'facebook', title: 'Facebook link', type: 'url', group: 'social' }),
    defineField({
      name: 'beeEnabled',
      title: 'Show the bee',
      type: 'boolean',
      group: 'bee',
      initialValue: true,
      description: 'The little bee in the corner of every page. Visitors tap it to send you feedback and ideas (they arrive in Inbox), and to see your recommendations.',
    }),
    defineField({
      name: 'beeGreeting',
      title: 'What the bee says',
      type: 'string',
      group: 'bee',
      initialValue: 'Got an idea, a wish or a kind word? Tell the bee.',
    }),
    defineField({
      name: 'beePicks',
      title: 'The bee recommends',
      type: 'array',
      group: 'bee',
      description: 'Up to four things to try. Change them whenever you like, e.g. this month’s special.',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'beePick',
          fields: [
            defineField({ name: 'title', title: 'Name', type: 'string', validation: (r) => r.required() }),
            defineField({ name: 'text', title: 'Why it’s good', type: 'string' }),
            defineField({ name: 'link', title: 'Link (optional)', type: 'string', description: 'A page on this site like /menu or /shop/pure-honey, or a full web address.' }),
          ],
        }),
      ],
      validation: (r) => r.max(4),
    }),
    defineField({
      name: 'googlePlaceId',
      title: 'Google Place ID',
      type: 'string',
      group: 'reviews',
      description:
        'Lets the website show your Google rating and best reviews, and link straight to “Write a review”. Find it by searching for the café at developers.google.com/maps/documentation/places/web-service/place-id (it starts with ChIJ…).',
    }),
    defineField({
      name: 'reviewLink',
      title: '“Leave a review” link (optional)',
      type: 'url',
      group: 'reviews',
      description: 'Only if you want the button to go somewhere other than Google, e.g. TripAdvisor.',
    }),
    defineField({
      name: 'seo',
      title: 'Default Google & sharing settings',
      type: 'seo',
      group: 'seo',
      description: 'Used on every page unless that page has its own.',
    }),
  ],
  preview: { prepare: () => ({ title: 'Site settings' }) },
})
